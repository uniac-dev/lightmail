import assert from "node:assert/strict";
import { MailSender } from "../dist/index.js";
const client = new MailSender(process.env.SENDER_TEST_TOKEN, { baseUrl: process.env.SENDER_TEST_URL });
const created = await client.domains.create({ name: "sdk.example.com" });
assert.equal(created.error, null);
assert.equal(created.data.status, "pending");
const verified = await client.domains.verify(created.data.id);
assert.equal(verified.error, null);
assert.equal(verified.data.status, "verified");
const credential = await client.apiKeys.create({ name: "SDK integration", domain_id: created.data.id });
assert.equal(credential.error, null);
const sender = new MailSender(credential.data.token, { baseUrl: process.env.SENDER_TEST_URL });
const input = { from: "SDK <hello@sdk.example.com>", to: "person@example.net", subject: "SDK integration", text: "This uses the real backend." };
const first = await sender.emails.send(input, { idempotencyKey: "sdk-integration" });
assert.equal(first.error, null);
const repeated = await sender.emails.send(input, { idempotencyKey: "sdk-integration" });
assert.equal(repeated.data.id, first.data.id);
const fetched = await sender.emails.get(first.data.id);
assert.equal(fetched.data.message.text, input.text);
const listed = await sender.emails.list();
assert.equal(listed.data.items.length, 1);
const forbidden = await sender.domains.list();
assert.equal(forbidden.error.status, 403);
const canceled = await sender.emails.cancel(first.data.id);
assert.equal(canceled.data.status, "canceled");
const revoked = await client.apiKeys.revoke(credential.data.key.id);
assert.equal(revoked.error, null);
assert.equal((await sender.emails.list()).error.status, 401);
console.log("TypeScript SDK / Go HTTP integration passed.");
